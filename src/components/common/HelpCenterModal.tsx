import React, { useState, useEffect, useMemo, useRef } from 'react';
import { UserRole, ManualChapter, ManualStep } from '../../types';
import { ROLE_MANUAL_CHAPTERS, getChaptersForRole, searchManualChapters } from '../../data/manualData';
import { ROLE_CONFIGS } from '../../lib/auth';
import { 
  X, 
  Search, 
  Play, 
  Pause, 
  Clock, 
  ShieldAlert, 
  CheckCircle2, 
  ExternalLink, 
  Download, 
  HelpCircle, 
  ChevronRight, 
  Video, 
  BookOpen, 
  Sparkles,
  VolumeX,
  FileText
} from 'lucide-react';

interface HelpCenterModalProps {
  isOpen: boolean;
  onClose: () => void;
  currentUserRole: UserRole;
  onNavigateTab?: (tab: string) => void;
}

const ALL_ROLES: UserRole[] = ['guest', 'client', 'technician', 'postal', 'admin', 'site'];

export const HelpCenterModal: React.FC<HelpCenterModalProps> = ({
  isOpen,
  onClose,
  currentUserRole,
  onNavigateTab
}) => {
  const [selectedRole, setSelectedRole] = useState<UserRole>(currentUserRole);
  const [searchQuery, setSearchQuery] = useState('');
  const [selectedChapterId, setSelectedChapterId] = useState<string>('');
  const [activeStepIndex, setActiveStepIndex] = useState<number>(0);
  const [videoError, setVideoError] = useState(false);
  const videoRef = useRef<HTMLVideoElement>(null);

  // Sync selected role when modal opens or user changes
  useEffect(() => {
    if (isOpen) {
      setSelectedRole(currentUserRole);
      setSearchQuery('');
      setVideoError(false);
    }
  }, [isOpen, currentUserRole]);

  // Compute available chapters based on role and search query
  const filteredChapters = useMemo(() => {
    if (searchQuery.trim()) {
      return searchManualChapters(searchQuery, selectedRole);
    }
    return getChaptersForRole(selectedRole);
  }, [selectedRole, searchQuery]);

  // Ensure selected chapter is always valid
  useEffect(() => {
    if (filteredChapters.length > 0) {
      const exists = filteredChapters.some(c => c.id === selectedChapterId);
      if (!exists) {
        setSelectedChapterId(filteredChapters[0].id);
        setActiveStepIndex(0);
        setVideoError(false);
      }
    } else {
      setSelectedChapterId('');
      setActiveStepIndex(0);
    }
  }, [filteredChapters, selectedChapterId]);

  const activeChapter: ManualChapter | undefined = useMemo(() => {
    return filteredChapters.find(c => c.id === selectedChapterId) || filteredChapters[0];
  }, [filteredChapters, selectedChapterId]);

  // Handle escape key
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'Escape' && isOpen) {
        onClose();
      }
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [isOpen, onClose]);

  if (!isOpen) return null;

  const handleStepClick = (index: number, step: ManualStep) => {
    setActiveStepIndex(index);
    if (videoRef.current && typeof step.timestampSeconds === 'number') {
      try {
        videoRef.current.currentTime = step.timestampSeconds;
        videoRef.current.play().catch(() => {});
      } catch {
        // Video might not be loaded
      }
    }
  };

  const handleJumpToTab = (tab?: string) => {
    if (tab && onNavigateTab) {
      onNavigateTab(tab);
      onClose();
    }
  };

  const handleDownloadQuickRef = () => {
    if (!activeChapter) return;
    const content = [
      `AJW Marine Electrical Services — Role Manual Quick Reference`,
      `Role: ${selectedRole.toUpperCase()} | Chapter: ${activeChapter.title}`,
      `Estimated Duration: ${activeChapter.durationMinutes} minutes`,
      ``,
      `SUMMARY:`,
      activeChapter.summary,
      ``,
      `KEY WORKFLOW STEPS:`,
      ...activeChapter.steps.map((s, idx) => 
        `${idx + 1}. [${s.timestampSeconds || 0}s] ${s.title}\n   ${s.description}${s.safetyTip ? `\n   ⚠️ SAFETY TIP: ${s.safetyTip}` : ''}${s.shortcut ? `\n   ⌨️ SHORTCUT: ${s.shortcut}` : ''}`
      ),
      ``,
      `---`,
      `Generated by AJWMES Solent Marine Workshop Management System`
    ].join('\n');

    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `ajwmes-manual-${selectedRole}-${activeChapter.id}.txt`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div 
      data-testid="help-center-modal" 
      className="fixed inset-0 z-50 flex items-center justify-center p-2 sm:p-4 md:p-6 bg-slate-950/80 backdrop-blur-md animate-in fade-in duration-200"
      role="dialog"
      aria-modal="true"
      aria-labelledby="help-center-title"
    >
      <div className="relative w-full max-w-6xl max-h-[92vh] flex flex-col bg-slate-900 border border-slate-800 rounded-3xl shadow-2xl overflow-hidden">
        {/* Header */}
        <div className="px-5 py-4 border-b border-slate-800/80 bg-slate-950/60 flex items-center justify-between gap-4 shrink-0">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-xl bg-amber-500/10 border border-amber-500/30 text-amber-400">
              <BookOpen className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 id="help-center-title" className="text-base sm:text-lg font-bold text-white">
                  Workshop User Manual &amp; Video Guides
                </h2>
                <span className="text-[10px] font-mono px-2 py-0.5 rounded-full bg-slate-800 text-slate-300 border border-slate-700">
                  Role: {ROLE_CONFIGS[selectedRole].label}
                </span>
              </div>
              <p className="text-xs text-slate-400">
                Playwright automated training clips, step checklists, and operational marine safety standards.
              </p>
            </div>
          </div>

          <button
            data-testid="close-help-modal-button"
            onClick={onClose}
            className="p-2 rounded-xl text-slate-400 hover:text-white hover:bg-slate-800 transition-colors cursor-pointer shrink-0"
            aria-label="Close user manual modal"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Role Tab Navigation & Search Bar */}
        <div className="px-5 py-3 border-b border-slate-800/60 bg-slate-950/30 flex flex-col md:flex-row items-stretch md:items-center justify-between gap-3 shrink-0">
          {/* Role Tabs */}
          <div 
            data-testid="manual-role-tabs" 
            className="flex items-center gap-1.5 overflow-x-auto pb-1 md:pb-0 scrollbar-none"
          >
            {ALL_ROLES.map((role) => {
              const isSelected = selectedRole === role;
              const isCurrent = currentUserRole === role;
              return (
                <button
                  key={role}
                  data-testid={`role-tab-${role}`}
                  onClick={() => {
                    setSelectedRole(role);
                    setVideoError(false);
                  }}
                  className={`flex items-center gap-1.5 px-3 py-1.5 rounded-xl text-xs font-semibold whitespace-nowrap transition-all cursor-pointer ${
                    isSelected
                      ? 'bg-amber-500/20 text-amber-300 border border-amber-500/50 shadow-sm shadow-amber-950'
                      : 'text-slate-400 hover:text-slate-200 hover:bg-slate-800/60 border border-transparent'
                  }`}
                >
                  <span className="capitalize">{ROLE_CONFIGS[role].label}</span>
                  {isCurrent && (
                    <span className="w-1.5 h-1.5 rounded-full bg-emerald-400" title="Your Current Active Role" />
                  )}
                </button>
              );
            })}
          </div>

          {/* Search Input */}
          <div className="relative min-w-[220px] max-w-xs">
            <Search className="absolute left-3 top-2.5 w-3.5 h-3.5 text-slate-400" />
            <input
              data-testid="manual-search-input"
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Search steps, CAD, lithium..."
              className="w-full pl-9 pr-7 py-1.5 text-xs bg-slate-950 border border-slate-800 rounded-xl text-slate-200 placeholder-slate-500 focus:outline-none focus:border-amber-500/60 transition-colors"
            />
            {searchQuery && (
              <button
                onClick={() => setSearchQuery('')}
                className="absolute right-2 top-2 text-slate-400 hover:text-white"
                title="Clear search"
              >
                <X className="w-3.5 h-3.5" />
              </button>
            )}
          </div>
        </div>

        {/* Modal Body: Two-Column Responsive Layout */}
        <div className="flex-1 min-h-0 grid grid-cols-1 lg:grid-cols-12 overflow-y-auto lg:overflow-hidden">
          {/* Left Column: Chapter Playlist & Text Breakdown (5 cols) */}
          <div className="lg:col-span-5 p-4 sm:p-5 border-b lg:border-b-0 lg:border-r border-slate-800/80 flex flex-col gap-4 overflow-y-auto">
            {/* Chapter Selection */}
            <div>
              <span className="text-[11px] font-mono uppercase tracking-wider text-slate-400 font-semibold mb-2 block">
                Manual Modules ({filteredChapters.length})
              </span>

              {filteredChapters.length === 0 ? (
                <div className="p-6 text-center rounded-2xl bg-slate-950/40 border border-slate-800/60 text-slate-400 text-xs">
                  No manual modules found matching &ldquo;{searchQuery}&rdquo;.
                </div>
              ) : (
                <div data-testid="manual-chapter-list" className="space-y-2">
                  {filteredChapters.map((chapter) => {
                    const isSelected = activeChapter?.id === chapter.id;
                    return (
                      <button
                        key={chapter.id}
                        data-testid={`chapter-item-${chapter.id}`}
                        onClick={() => {
                          setSelectedChapterId(chapter.id);
                          setActiveStepIndex(0);
                          setVideoError(false);
                        }}
                        className={`w-full text-left p-3 rounded-2xl border transition-all cursor-pointer flex items-start justify-between gap-3 ${
                          isSelected
                            ? 'bg-slate-800/90 border-amber-500/50 shadow-md shadow-slate-950 text-white'
                            : 'bg-slate-950/40 border-slate-800/80 hover:bg-slate-800/40 text-slate-300'
                        }`}
                      >
                        <div className="space-y-1 min-w-0">
                          <h3 className="text-xs font-bold truncate leading-snug">
                            {chapter.title}
                          </h3>
                          <p className="text-[11px] text-slate-400 line-clamp-2 leading-relaxed">
                            {chapter.summary}
                          </p>
                          <div className="flex items-center gap-3 pt-1 text-[10px] text-slate-400 font-mono">
                            <span className="flex items-center gap-1 text-amber-400/90">
                              <Clock className="w-3 h-3" />
                              {chapter.durationMinutes} min
                            </span>
                            <span>•</span>
                            <span>{chapter.steps.length} Steps</span>
                          </div>
                        </div>
                        <ChevronRight className={`w-4 h-4 shrink-0 transition-transform ${isSelected ? 'text-amber-400 translate-x-0.5' : 'text-slate-500'}`} />
                      </button>
                    );
                  })}
                </div>
              )}
            </div>

            {/* Step-by-Step Interactive Checklist */}
            {activeChapter && (
              <div className="mt-2 space-y-2.5">
                <div className="flex items-center justify-between">
                  <span className="text-[11px] font-mono uppercase tracking-wider text-slate-400 font-semibold">
                    Step-by-Step Procedure
                  </span>
                  <span className="text-[10px] text-slate-400 font-mono">
                    Step {activeStepIndex + 1} of {activeChapter.steps.length}
                  </span>
                </div>

                <div data-testid="step-checklist" className="space-y-2">
                  {activeChapter.steps.map((step, idx) => {
                    const isActive = activeStepIndex === idx;
                    return (
                      <div
                        key={step.id}
                        data-testid={`step-row-${step.id}`}
                        onClick={() => handleStepClick(idx, step)}
                        className={`p-3 rounded-xl border text-xs transition-all cursor-pointer ${
                          isActive
                            ? 'bg-amber-950/30 border-amber-500/50 text-amber-200'
                            : 'bg-slate-950/30 border-slate-800/60 hover:bg-slate-800/30 text-slate-300'
                        }`}
                      >
                        <div className="flex items-center justify-between gap-2 mb-1">
                          <div className="flex items-center gap-2">
                            <span className={`w-5 h-5 rounded-full flex items-center justify-center text-[10px] font-mono font-bold shrink-0 ${
                              isActive ? 'bg-amber-400 text-slate-950' : 'bg-slate-800 text-slate-400'
                            }`}>
                              {idx + 1}
                            </span>
                            <span className="font-bold text-white">{step.title}</span>
                          </div>
                          {typeof step.timestampSeconds === 'number' && (
                            <span className="text-[10px] font-mono text-slate-400 shrink-0">
                              {Math.floor(step.timestampSeconds / 60)}:{(step.timestampSeconds % 60).toString().padStart(2, '0')}
                            </span>
                          )}
                        </div>

                        <p className="text-[11px] text-slate-400 leading-relaxed pl-7">
                          {step.description}
                        </p>

                        {step.safetyTip && (
                          <div className="mt-2 ml-7 p-2 rounded-lg bg-rose-950/40 border border-rose-500/30 text-rose-300 text-[10px] flex items-start gap-1.5">
                            <ShieldAlert className="w-3.5 h-3.5 shrink-0 text-rose-400 mt-0.5" />
                            <span><strong>Marine Safety:</strong> {step.safetyTip}</span>
                          </div>
                        )}

                        {step.shortcut && (
                          <div className="mt-1.5 ml-7 text-[10px] text-cyan-400/90 font-mono">
                            ⌨️ {step.shortcut}
                          </div>
                        )}
                      </div>
                    );
                  })}
                </div>
              </div>
            )}
          </div>

          {/* Right Column: Training Video Screen & Quick Actions (7 cols) */}
          <div className="lg:col-span-7 p-4 sm:p-5 flex flex-col gap-4 overflow-y-auto bg-slate-950/20">
            {activeChapter ? (
              <>
                {/* Video Player Display Container */}
                <div 
                  data-testid="video-player-container" 
                  className="relative w-full aspect-video rounded-2xl overflow-hidden bg-slate-950 border border-slate-800 shadow-xl flex flex-col justify-between"
                >
                  {!videoError && activeChapter.videoUrl ? (
                    <video
                      ref={videoRef}
                      data-testid="video-element"
                      className="w-full h-full object-cover"
                      controls
                      playsInline
                      poster={activeChapter.posterUrl}
                      onError={() => setVideoError(true)}
                    >
                      <source src={activeChapter.videoUrl.replace(/\.mp4$/, '.webm')} type="video/webm" />
                      <source src={activeChapter.videoUrl} type="video/mp4" />
                      {activeChapter.vttUrl && (
                        <track 
                          kind="subtitles" 
                          src={activeChapter.vttUrl} 
                          srcLang="en" 
                          label="English Steps" 
                          default 
                        />
                      )}
                    </video>
                  ) : (
                    /* Offline / Fallback Video Card */
                    <div 
                      data-testid="video-fallback-banner" 
                      className="absolute inset-0 flex flex-col items-center justify-center p-6 text-center bg-gradient-to-br from-slate-950 via-slate-900 to-slate-950 text-slate-300"
                    >
                      <div className="p-3 rounded-2xl bg-amber-500/10 border border-amber-500/30 text-amber-400 mb-3">
                        <Video className="w-8 h-8" />
                      </div>
                      <h4 className="text-sm font-bold text-white mb-1">
                        Playwright Training Vignette
                      </h4>
                      <p className="text-xs text-slate-400 max-w-sm mb-4 leading-relaxed">
                        Full 1080p demonstration video is queued for background streaming or will generate upon running <code className="font-mono text-amber-300">npm run record:manuals</code>.
                      </p>
                      <div className="flex items-center gap-2 text-[11px] font-mono text-slate-400 bg-slate-950 px-3 py-1.5 rounded-xl border border-slate-800">
                        <VolumeX className="w-3.5 h-3.5 text-slate-400" />
                        <span>Silent High-Contrast HUD Demo Track</span>
                      </div>
                    </div>
                  )}

                  {/* Animated Lower-Third HUD Overlay Mirror */}
                  <div className="absolute bottom-3 left-3 right-3 pointer-events-none">
                    <div className="px-3 py-2 rounded-xl bg-slate-950/90 border border-amber-500/40 backdrop-blur-md shadow-lg flex items-center justify-between gap-3 text-xs">
                      <div className="flex items-center gap-2 min-w-0">
                        <span className="px-2 py-0.5 rounded bg-amber-400 text-slate-950 font-bold font-mono text-[10px] shrink-0">
                          Step {activeStepIndex + 1}
                        </span>
                        <span className="text-white font-medium truncate">
                          {activeChapter.steps[activeStepIndex]?.title}
                        </span>
                      </div>
                      <span className="text-[10px] text-amber-400/90 font-mono shrink-0">
                        AJWMES Live Manual
                      </span>
                    </div>
                  </div>
                </div>

                {/* Chapter Overview & Metadata */}
                <div className="p-4 rounded-2xl bg-slate-950/40 border border-slate-800/60 space-y-2">
                  <div className="flex flex-wrap items-center justify-between gap-2">
                    <h3 className="text-sm font-bold text-white">
                      {activeChapter.title}
                    </h3>
                    <div className="flex items-center gap-2">
                      <span className="text-[10px] font-mono px-2 py-0.5 rounded-md bg-slate-800 text-slate-300 border border-slate-700">
                        {ROLE_CONFIGS[activeChapter.role].badge}
                      </span>
                      <span className="text-[10px] font-mono text-amber-400 flex items-center gap-1">
                        <Clock className="w-3 h-3" />
                        {activeChapter.durationMinutes} min
                      </span>
                    </div>
                  </div>
                  <p className="text-xs text-slate-300 leading-relaxed">
                    {activeChapter.summary}
                  </p>
                </div>

                {/* Bottom Actions Bar */}
                <div className="mt-auto pt-3 border-t border-slate-800/80 flex flex-wrap items-center justify-between gap-2">
                  {/* Jump To Tab Feature */}
                  {activeChapter.jumpTab && (
                    <button
                      data-testid="jump-to-feature-btn"
                      onClick={() => handleJumpToTab(activeChapter.jumpTab)}
                      className="flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-sky-600 hover:bg-sky-500 text-white font-bold text-xs transition-colors shadow-md shadow-sky-600/20 cursor-pointer"
                    >
                      <span>Open {activeChapter.title.split(' ')[0]} Workspace</span>
                      <ExternalLink className="w-3.5 h-3.5" />
                    </button>
                  )}

                  {/* Download Quick Reference Card */}
                  <button
                    data-testid="download-quickref-btn"
                    onClick={handleDownloadQuickRef}
                    className="flex items-center gap-1.5 px-3 py-2 rounded-xl bg-slate-800 hover:bg-slate-750 text-slate-200 border border-slate-700 text-xs font-semibold transition-colors cursor-pointer ml-auto"
                    title="Download Text Quick Reference Card"
                  >
                    <Download className="w-3.5 h-3.5 text-amber-400" />
                    <span>Download Quick-Ref Card</span>
                  </button>
                </div>
              </>
            ) : (
              <div className="flex-1 flex items-center justify-center p-8 text-center text-slate-400 text-xs">
                Select a module from the left list to view video demonstrations and procedures.
              </div>
            )}
          </div>
        </div>
      </div>
    </div>
  );
};
